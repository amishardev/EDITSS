"""
Watch-the-render check: does the picture actually land on the music?

For every rendered Reel in out/reels:
  1. audio alignment  - cross-correlates the Reel's audio with the same span of the master (should be 0 ms)
  2. cut timing       - detects hard cuts from frame differences and compares them with the planned cuts
  3. beat lock        - folds frame brightness over the beat grid and reports where the light peaks
                        relative to the kick (for shots built on lamps passing on the kick)
usage: python3 scripts/sync_check.py [R01 R09 ...]
writes: reels/SYNC_REPORT.md
"""
import json, subprocess, sys, os
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FPS = 30
BEAT = 60 / 128
SR = 22050


def run(cmd):
    return subprocess.run(cmd, capture_output=True, check=True).stdout


def audio(path, start=None, dur=None):
    cmd = ["ffmpeg", "-v", "error"]
    if start is not None:
        cmd += ["-ss", f"{start:.4f}"]
    cmd += ["-i", path]
    if dur is not None:
        cmd += ["-t", f"{dur:.4f}"]
    cmd += ["-ac", "1", "-ar", str(SR), "-f", "f32le", "-"]
    return np.frombuffer(run(cmd), dtype=np.float32)


def frames(path, w=54, h=96):
    raw = run(["ffmpeg", "-v", "error", "-i", path, "-vf", f"scale={w}:{h}", "-pix_fmt", "gray", "-f", "rawvideo", "-"])
    return np.frombuffer(raw, dtype=np.uint8).reshape(-1, h, w).astype(np.float32)


def lag_ms(a, b, max_ms=200):
    n = min(len(a), len(b), SR * 8)
    a, b = a[:n], b[:n]
    m = int(SR * max_ms / 1000)
    best, best_l = -1e9, 0
    for l in range(-m, m + 1, 11):
        x = a[max(0, l):n + min(0, l)]
        y = b[max(0, -l):n - max(0, l)]
        c = float(np.dot(x, y))
        if c > best:
            best, best_l = c, l
    return best_l / SR * 1000


def main():
    want = [w.upper() for w in sys.argv[1:]]
    reels = json.load(open(os.path.join(ROOT, "reels/reels.json")))
    analysis = json.load(open(os.path.join(ROOT, "analysis/moonlight.analysis.json")))
    kicks = np.array(analysis["kicks"])
    master = os.path.join(ROOT, "public/audio/moonlight.mp3")
    lines = ["# Sync report", "", "Generated by `python3 scripts/sync_check.py` from the rendered files in `out/reels/`.", "",
             "| Reel | audio offset | planned hard cuts | matched (±1 frame) | worst cut error | biggest visual change | light peak vs kick |", "|---|---|---|---|---|---|---|"]
    big_events = [(e["t"], e["note"]) for e in analysis["events"] if e["weight"] >= 0.7]
    for r in reels:
        if want and r["id"] not in want:
            continue
        path = os.path.join(ROOT, "out/reels", f"{r['composition']}.mp4")
        if not os.path.exists(path):
            continue
        start = round(float(r["song_timestamp"].split(" ")[0].split(":")[0]) * 60 + float(r["song_timestamp"].split(" ")[0].split(":")[1]), 3)
        start = round(start * FPS) / FPS
        a_reel = audio(path)
        a_master = audio(master, start, r["duration_s"])
        off = lag_ms(a_reel, a_master)

        F = frames(path)
        diff = np.abs(np.diff(F, axis=0)).mean(axis=(1, 2))
        # a cut is a frame difference far above its neighbourhood
        med = np.array([np.median(diff[max(0, i - 8):i + 9]) for i in range(len(diff))])
        cut_frames = [i + 1 for i in range(len(diff)) if diff[i] > max(6.0, 3.0 * med[i]) and diff[i] == diff[max(0, i - 2):i + 3].max()]
        planned = [round(s["reel_time"] * FPS) for s in r["shot_order"][1:] if s["transition_in"] in ("cut", "lampwipe", "flash")]
        errs = []
        for p in planned:
            near = [c - p for c in cut_frames if abs(c - p) <= 3]
            errs.append(min(near, key=abs) if near else None)
        matched = sum(1 for e in errs if e is not None and abs(e) <= 1)
        worst = max((abs(e) for e in errs if e is not None), default=0)
        missing = sum(1 for e in errs if e is None)

        # beat lock: fold brightness derivative on the beat grid, only where kicks exist
        lum = F.mean(axis=(1, 2))
        t = start + np.arange(len(lum)) / FPS
        ks = kicks[(kicks >= t[0]) & (kicks <= t[-1])]
        peak = "-"
        if len(ks) >= 8:
            phases = ((t - ks[0]) / BEAT) % 1.0
            bins = np.zeros(16)
            cnt = np.zeros(16)
            for ph, v in zip(phases, lum - np.convolve(lum, np.ones(15) / 15, mode="same")):
                b = int(ph * 16) % 16
                bins[b] += v
                cnt[b] += 1
            prof = bins / np.maximum(cnt, 1)
            pb = int(np.argmax(prof))
            ms = (pb if pb < 8 else pb - 16) * BEAT / 16 * 1000
            peak = f"{ms:+.0f} ms"
        # where is the single largest frame-to-frame change, and what music is there?
        bi = int(np.argmax(diff)) + 1
        bt = start + bi / FPS
        near = min(big_events, key=lambda e: abs(e[0] - bt))
        dt = (bt - near[0]) * 1000
        big = f"{bt // 60:.0f}:{bt % 60:05.2f}" + (f" = {near[1].split(' (')[0]} ({dt:+.0f} ms)" if abs(dt) < 120 else " (on a cut)")
        lines.append(f"| {r['number']}. {r['name']} | {off:+.1f} ms | {len(planned)} | {matched}{f' ({missing} not detected)' if missing else ''} | {worst} fr | {big} | {peak} |")
        print(lines[-1])
    lines += ["", "Notes:", "- audio offset = how far the Reel's soundtrack is from the master at the same song time (0 means the picture timing and the music share one clock).",
              "- cuts that sit under a flash or between two dark shots can be invisible to the detector; those count as 'not detected', not as errors.",
              "- biggest visual change = the frame with the largest picture change in the whole Reel and the nearest strong musical event (drop, impact, kick-out...). For drop Reels it should sit on the drop.",
              "- light peak vs kick = where the frame is brightest inside an average beat (lamps passing / punches). Values within one 16th (±29 ms) mean the light hits on the kick; only meaningful for Reels whose picture pulses on the kick."]
    open(os.path.join(ROOT, "reels/SYNC_REPORT.md"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
